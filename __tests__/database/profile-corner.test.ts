import { expect, it } from 'vitest';
import { readFileSync } from 'node:fs';
import { createDormDatabase, testUid } from '../helpers/dormspace-db';
import { EMPTY_CORNER } from '../../lib/profile-corner';

it('persists cards, enforces ownership, counts real votes and serializes the last plan spot', async () => {
  const db = await createDormDatabase(4);
  const sql = readFileSync('supabase/migrations/20261027040000_profile_corners.sql', 'utf8');
  const call = async (student: number, action = 'read', username: string | null = null, payload = {}) =>
    (await db.query<any>('SELECT public.socialu_profile_corner($1,$2,$3,$4) AS result', [testUid(student), action, username, JSON.stringify(payload)])).rows[0].result;
  const tomorrow = () => new Date(Date.now() + 86400000).toISOString();
  const pollInput = () => ({ question: 'Coffee or study group?', options: ['Coffee', 'Study group'], endsAt: tomorrow() });
  const planInput = () => ({ title: 'Study break', location: 'Library', startsAt: tomorrow(), capacity: 2 });
  try {
    await db.exec(sql); await db.exec(sql);
    expect(await call(1)).toEqual(EMPTY_CORNER);
    const vibe = await call(1, 'save_vibe', null, { text: ' On campus ', icon: 'sun' });
    expect(vibe.vibe.text).toBe('On campus');
    const goals = [{ id: 'one', text: 'Try a club', done: false }];
    await call(1, 'save_goals', null, { goals });
    expect((await call(2, 'read', 'dorm1')).goals).toEqual(goals);
    await expect(call(2, 'save_vibe', 'dorm1', { text: 'Forged', icon: 'coffee' })).rejects.toThrow(/own cards/);
    await expect(call(2, 'save_goals', 'dorm1', { goals: [] })).rejects.toThrow(/own cards/);
    await expect(call(1, 'save_goals', null, { goals: [goals[0], goals[0]] })).rejects.toThrow(/valid goals/);
    await expect(call(1, 'save_vibe', null, { text: 'x'.repeat(61), icon: 'sun' })).rejects.toThrow();
    await expect(call(1, 'save_goals', null, { goals: [{ id: 'one', text: 'x', done: 'true' }] })).rejects.toThrow();
    let result = await call(1, 'create_poll', null, pollInput());
    const pollId = result.poll.id;
    expect(result.poll.totalVotes).toBe(0);
    await expect(call(1, 'vote', null, { id: pollId, choice: 0 })).rejects.toThrow(/Classmates/);
    await call(2, 'vote', 'dorm1', { id: pollId, choice: 0 });
    result = await call(2, 'vote', 'dorm1', { id: pollId, choice: 1 });
    expect(result.poll.totalVotes).toBe(1); expect(result.poll.choice).toBe(1);
    expect(result.poll.options.map((o: any) => o.votes)).toEqual([0, 1]);
    result = await call(3, 'vote', 'dorm1', { id: pollId, choice: 0 });
    expect(result.poll.totalVotes).toBe(2);
    expect((await call(4, 'read', 'dorm1')).poll.choice).toBeNull();
    await expect(call(2, 'close_poll', 'dorm1', { id: pollId })).rejects.toThrow(/own cards/);
    await call(1, 'close_poll', null, { id: pollId });
    await expect(call(4, 'vote', 'dorm1', { id: pollId, choice: 0 })).rejects.toThrow(/ended/);
    result = await call(1, 'create_poll', null, pollInput());
    expect(result.poll.id).not.toBe(pollId); expect(result.poll.totalVotes).toBe(0);
    await expect(call(2, 'vote', 'dorm1', { id: pollId, choice: 0 })).rejects.toThrow(/no longer/);
    await expect(call(1, 'create_poll', null, { ...pollInput(), options: ['Coffee', ' coffee '] })).rejects.toThrow();
    await expect(call(1, 'create_poll', null, { ...pollInput(), endsAt: '2020-01-01' })).rejects.toThrow();
    result = await call(1, 'create_plan', null, planInput());
    const planId = result.plan.id;
    expect(result.plan.joinedCount).toBe(1); expect(result.plan.joined).toBe(true);
    // Both requests compete for one remaining seat; the profile row lock serializes them.
    const joins = await Promise.allSettled([call(2, 'join_plan', 'dorm1', { id: planId }), call(3, 'join_plan', 'dorm1', { id: planId })]);
    expect(joins.filter(item => item.status === 'fulfilled')).toHaveLength(1);
    expect(joins.filter(item => item.status === 'rejected')).toHaveLength(1);
    result = await call(2, 'read', 'dorm1');
    expect(result.plan.joinedCount).toBe(2);
    const guest = result.plan.people[0].username === 'dorm2' ? 2 : 3;
    expect((await call(guest, 'join_plan', 'dorm1', { id: planId })).plan.joinedCount).toBe(2);
    await expect(call(4, 'join_plan', 'dorm1', { id: planId })).rejects.toThrow(/full/);
    await call(guest, 'leave_plan', 'dorm1', { id: planId });
    expect((await call(4, 'join_plan', 'dorm1', { id: planId })).plan.joinedCount).toBe(2);
    await expect(call(4, 'cancel_plan', 'dorm1', { id: planId })).rejects.toThrow(/own cards/);
    await db.query('INSERT INTO socialu.student_blocks(blocker_id,blocked_id) VALUES(1,4)');
    await expect(call(4, 'read', 'dorm1')).rejects.toThrow(/not available/);
    await expect(call(4, 'join_plan', 'dorm1', { id: planId })).rejects.toThrow(/not available/);
    expect((await call(1)).plan.joinedCount).toBe(1);
    await call(2, 'join_plan', 'dorm1', { id: planId });
    await db.query('DELETE FROM socialu.student_blocks WHERE blocker_id=1 AND blocked_id=4');
    result = await call(4, 'read', 'dorm1');
    expect(result.plan.joinedCount).toBe(2); expect(result.plan.joined).toBe(false);
    await call(1, 'cancel_plan', null, { id: planId });
    expect((await call(2, 'read', 'dorm1')).plan).toBeNull();
    await expect(call(2, 'join_plan', 'dorm1', { id: planId })).rejects.toThrow(/no longer open/);
    result = await call(1, 'create_plan', null, planInput());
    expect(result.plan.joinedCount).toBe(1); expect(result.plan.id).not.toBe(planId);
    await expect(call(2, 'leave_plan', 'dorm1', { id: planId })).rejects.toThrow(/no longer available/);
    await db.query("UPDATE socialu.profile_corner_plans SET starts_at=now()-interval '1 hour' WHERE plan_id=$1", [result.plan.id]);
    await expect(call(2, 'join_plan', 'dorm1', { id: result.plan.id })).rejects.toThrow(/no longer open/);
    await expect(call(1, 'create_plan', null, { ...planInput(), capacity: 2.5 })).rejects.toThrow();
    await db.exec(sql);
    result = await call(2, 'read', 'dorm1');
    expect(result.vibe.text).toBe('On campus'); expect(result.goals).toEqual(goals);
    await call(1, 'save_goals', null, { goals: [{ ...goals[0], done: true }] });
    expect((await call(2, 'read', 'dorm1')).goals[0].done).toBe(true);
    expect((await call(1, 'save_vibe', null, { clear: true })).vibe).toBeNull();
    await db.exec('SET ROLE authenticated');
    await expect(call(1)).rejects.toThrow(/permission denied/);
    await expect(db.query('SELECT * FROM socialu.profile_corners')).rejects.toThrow(/permission denied/);
  } finally { await db.close(); }
}, 30000);

// Only emoji parts: pictographs, skin tones, joiners, the emoji style selector and flag tags; letters, digits
// and spaces never match. Intl.Segmenter then makes sure the value is a single emoji, not several.
const EMOJI_ONLY = /^(?=.*\p{Extended_Pictographic})(?:\p{Extended_Pictographic}|\p{Emoji_Modifier}|‍|️|[\u{E0020}-\u{E007F}])+$/u;

export const EMOJI_REQUIRED = 'Choose an emoji to send.';

export function isSingleEmoji(value: unknown): value is string {
  if (typeof value !== 'string' || [...value].length > 16 || !EMOJI_ONLY.test(value)) return false;
  return [...new Intl.Segmenter(undefined, { granularity: 'grapheme' }).segment(value)].length === 1;
}


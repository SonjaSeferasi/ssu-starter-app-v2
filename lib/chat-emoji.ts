export const CHAT_EMOJIS: ChatEmoji[] = LIST.map(([emoji, name, keywords]) => ({ emoji, name, keywords }));

// Every word typed must appear in the emoji's name or extra words ("laugh" finds 😂).
export function searchEmojis(query: string) {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return CHAT_EMOJIS;
  return CHAT_EMOJIS.filter(({ name, keywords }) => {
    const text = `${name} ${keywords}`;
    return words.every((word) => text.includes(word));
  });
}

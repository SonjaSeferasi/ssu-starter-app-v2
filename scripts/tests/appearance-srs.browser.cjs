// Actual local UI in Edge, with intercepted API fixtures. No hosted account/data writes.
const { chromium } = require(process.env.SOCIALU_PLAYWRIGHT_MODULE || 'playwright');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const base = process.env.SOCIALU_TEST_URL || 'http://127.0.0.1:3038';
const output = process.env.SOCIALU_EVIDENCE_DIR || 'tmp/appearance-evidence';
(async () => {
  fs.mkdirSync(output, { recursive: true });
  const browser = await chromium.launch({ headless: true, executablePath: process.env.SOCIALU_BROWSER_EXECUTABLE });
  const checks = [], errors = [], writes = [], presenceWrites = [];
  const themes = { alice: 'light', bob: 'light' };
  let failSave = false, failLoad = false;
  const room = { appearance: { outfitId: '1', faceId: '1', avatarId: 'campus-v4-female-1-1-natural' }, outfits: [{ id: '1', name: 'Campus', assetKey: 'sample-campus' }], faces: [{ id: '1', assetKey: 'sample-smile', initial: true }], activities: [] };
  async function setup(context) {
    await context.addInitScript(() => { if (!localStorage.getItem('access_token')) localStorage.setItem('access_token', 'alice'); });
    await context.route('**/api/**', async route => {
      const req = route.request(), path = new URL(req.url()).pathname;
      let status = 200, data = { members: [], posts: [], hasMore: false };
      if (path === '/api/preferences/appearance') {
        const owner = req.headers().authorization?.replace('Bearer ', '');
        if (req.method() === 'PUT') {
          const theme = req.postDataJSON().theme; writes.push({ owner, theme });
          if (failSave) status = 503; else themes[owner] = theme;
        } else if (failLoad) status = 503;
        data = status === 200 ? { theme: themes[owner] || 'light' } : { error: 'Deliberate fixture failure' };
      } else if (path === '/api/auth/session') data = { community: { name: 'Local QA fixture' } };
      else if (path === '/api/preferences') data = { position: 'side' };
      else if (path === '/api/preferences/screen-theme') data = { backgroundTheme: null, headerTheme: null };
      else if (path === '/api/game-room') data = room;
      else if (path === '/api/jumpyland') data = { completed: [], balance: 0 };
      else if (path === '/api/message-notifications') data = { notifications: [] };
      else if (path.includes('invitations')) data = { invitations: [] };
      else if (path === '/api/notifications') data = { unread: 0, notifications: [] };
      else if (path === '/api/points') data = { balance: 0 };
      else if (path === '/api/profile') data = { profile: null, defaults: { fullName: 'Local QA Fixture', username: 'local_qa' } };
      else if (path === '/api/game-participation') data = { count: 0, qualifiedToday: false, forgivenRemaining: 3, rewardPoints: 10, earnedPointsToday: 0, leaderboards: {} };
    if (path === '/api/game-room/presence') {
      if (!['GET','HEAD'].includes(req.method())) presenceWrites.push({method:req.method(),path});
      await route.fulfill({status:200,contentType:'application/json',body:JSON.stringify({friends:[],visible:true})});return;
    }
      if (!['GET', 'HEAD'].includes(req.method()) && path !== '/api/preferences/appearance') writes.push({ unexpected: path });
      await route.fulfill({ status, contentType: 'application/json', body: JSON.stringify(data) });
    });
  }
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await setup(context);
  const page = await context.newPage(); page.setDefaultTimeout(30000);
  page.on('pageerror', e => errors.push(e.message));
  const button = name => page.getByRole('button', { name, exact: true });
  const appearance = value => page.waitForFunction(value => document.documentElement.dataset.appearance === value, value);
  const open = async () => { const close = button('Close'); if (!(await close.isVisible())) await button('Preferences').click(); };
  try {
    await page.goto(base + '/#create-text-post');
    await page.getByRole('textbox', { name: 'Post text', exact: true }).fill('Keep this unfinished draft');
    await open(); await appearance('light');
    assert.equal(await button('☀ Light').getAttribute('aria-pressed'), 'true');
    checks.push('627.1/627.2: Light and Dark available; new fixture account defaults to Light');
    await button('☾ Dark').click();
    await page.waitForFunction(() => !document.querySelector('[aria-label="Appearance"] button')?.disabled);
    await appearance('dark');
    assert.equal(themes.alice, 'dark');
    assert.equal(await page.getByRole('textbox', { name: 'Post text', exact: true }).inputValue(), 'Keep this unfinished draft');
    assert.equal(await page.locator('[data-navigation]').getAttribute('data-theme-dark'), 'true');
    checks.push('627.3/627.9: Dark applied and automatically saved without navigation or lost draft');
    await page.screenshot({ path: output + '/dark-preferences.png' });
    failSave = true; await button('☀ Light').click();
    await page.getByRole('alert').filter({ hasText: 'Light is showing' }).waitFor();
    assert.equal(themes.alice, 'dark'); await appearance('light');
    await page.screenshot({ path: output + '/save-failure.png' });
    failSave = false; await button('Retry appearance').click();
    await page.waitForFunction(() => !document.querySelector('[aria-label="Appearance"] button')?.disabled);
    assert.deepEqual(writes.slice(-2).map(x => x.theme), ['light', 'light']);
    assert.equal(themes.alice, 'light');
    checks.push('627.7/627.8: failed Light save explains unsaved state; Retry submits exactly Light');
    await button('☾ Dark').click(); await appearance('dark');
    await page.waitForFunction(() => !document.querySelector('[aria-label="Appearance"] button')?.disabled);
    await button('Close').click(); await page.getByRole('link', { name: 'Game Room', exact: false }).first().click();
    await page.getByRole('region', { name: 'Game Room background' }).waitFor(); await appearance('dark');
    checks.push('627.5: selected Dark retained during client navigation to Game Room');
    const originalRoom = JSON.stringify(room), beforeWrites = writes.length;
    await button('Adventure Sky').click();
    assert.equal(await page.locator('[data-room-background]').getAttribute('data-room-background'), 'adventure-sky');
    await page.reload(); await button('Adventure Sky').waitFor();
    assert.equal(await button('Adventure Sky').getAttribute('aria-pressed'), 'true');
    assert.equal(writes.length, beforeWrites); assert.equal(JSON.stringify(room), originalRoom);
    await page.screenshot({ path: output + '/adventure-sky-dark.png' });
    checks.push('629.3: Adventure Sky persists on reload; no account/game/points/avatar writes');
    await page.setViewportSize({ width: 390, height: 844 });
    const choices = page.getByRole('region', { name: 'Game Room background' });
    await choices.scrollIntoViewIfNeeded();
    assert.ok(await choices.evaluate(el => el.getBoundingClientRect().right <= innerWidth + 1));
    await page.screenshot({ path: output + '/background-mobile.png' });
    checks.push('629.3: background chooser fits 390px viewport');
    await page.setViewportSize({ width: 1440, height: 1000 });
    const other = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
    await setup(other); const otherPage = await other.newPage();
    await otherPage.goto(base + '/game-room');
    await otherPage.waitForFunction(() => document.documentElement.dataset.appearance === 'dark');
    await otherPage.getByRole('button', { name: 'Campus Day', exact: true }).waitFor();
    assert.equal(await otherPage.getByRole('button', { name: 'Campus Day', exact: true }).getAttribute('aria-pressed'), 'true');
    checks.push('627.4/629.3: fresh browser context restores account Dark, but defaults its own device background to Campus Day (fixture-backed)');
    await other.close();
    await page.evaluate(() => { localStorage.setItem('access_token', 'bob'); window.dispatchEvent(new Event('socialu-session-changed')); });
    await appearance('light'); await open();
    await page.waitForFunction(() => !document.querySelector('[aria-label="Appearance"] button')?.disabled);
    assert.equal(themes.bob, 'light'); checks.push('627.4: account switch resets appearance and loads the new account preference');
    failLoad = true; await page.reload(); await open();
    await page.getByRole('alert').filter({ hasText: 'saved appearance could not be loaded' }).waitFor();
    failLoad = false; await button('Retry appearance').click();
    await page.waitForFunction(() => !document.querySelector('[aria-label="Appearance"] button')?.disabled);
    assert.equal(await page.getByRole('alert').filter({ hasText: 'saved appearance could not be loaded' }).count(), 0);
    checks.push('627.4: failed initial preference load is visible and can be retried');
    await button('Close').click();
    await page.evaluate(() => localStorage.setItem('socialu.game-room.background', 'invalid-value'));
    await page.reload(); await button('Campus Day').waitFor();
    assert.equal(await button('Campus Day').getAttribute('aria-pressed'), 'true');
    checks.push('629.3: corrupt local background preference safely defaults to Campus Day');
    await page.goto(base + '/game-1');
    await button('How to play').click();
    const instructions = page.getByRole('dialog', { name: 'How to play' });
    await instructions.waitFor();
    const lightMenu = await instructions.evaluate(el => getComputedStyle(el).backgroundColor);
    const artworkBefore = await page.locator('canvas').evaluateAll(elements => elements.map(el => ({ width: el.width, height: el.height, filter: getComputedStyle(el).filter })));
    themes.bob = 'dark';
    await page.evaluate(() => window.dispatchEvent(new Event('socialu-session-changed')));
    await appearance('dark');
    const darkMenu = await instructions.evaluate(el => getComputedStyle(el).backgroundColor);
    assert.notEqual(darkMenu, lightMenu);
    assert.deepEqual(await page.locator('canvas').evaluateAll(elements => elements.map(el => ({ width: el.width, height: el.height, filter: getComputedStyle(el).filter }))), artworkBefore);
    assert.equal(await instructions.isVisible(), true);
    await page.screenshot({ path: output + '/jumpyland-dark-menu.png' });
    checks.push('627.6: Jumpyland instructions change to Dark without closing the dialog or changing canvas dimensions/filter');
    assert.deepEqual(errors, []); assert.ok(!writes.some(x => x.unexpected));
    fs.writeFileSync(output + '/results.json', JSON.stringify({ evidence: 'Local Edge with intercepted API fixtures, not hosted persistence or physical-device acceptance.', checks, errors, writes, presenceWrites }, null, 2));
    console.log(JSON.stringify({ passed: checks.length, checks }, null, 2));
  } catch (error) {
    await page.screenshot({ path: output + '/failure.png' }); console.log(JSON.stringify({ checks, errors, url: page.url() })); throw error;
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
